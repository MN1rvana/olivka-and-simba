import type { CatId } from './cats.ts';
import manifest from './photos.json';

/** Who is in the photo. "both" means Olivka and Simba together. */
export type PhotoCat = CatId | 'both';

export interface Photo {
  id: string;
  cat: PhotoCat;
  /** Size of the largest file, used for width/height so the browser reserves space before it loads. */
  width: number;
  height: number;
  /** Every width that exists on disk, e.g. [480, 960, 1600]. */
  widths: readonly number[];
  alt: string;
  caption?: string;
  /** A 16px-wide WebP as a data URI, shown blurred while the real image loads. */
  placeholder: string;
}

const PHOTO_CATS: readonly string[] = ['olivka', 'simba', 'both'] satisfies PhotoCat[];

function isPhotoCat(value: string): value is PhotoCat {
  return PHOTO_CATS.includes(value);
}

/*
 * photos.json is generated by `npm run photos` and then edited by hand
 * (alt text, captions), so check it once at load time rather than trusting
 * the cast. A typo fails loudly in development instead of quietly in production.
 */
export const photos: readonly Photo[] = manifest.map((entry) => {
  if (!isPhotoCat(entry.cat)) {
    throw new Error(`photos.json: "${entry.cat}" on ${entry.id} isn't olivka, simba or both`);
  }

  return { ...entry, cat: entry.cat };
});

export function getPhoto(id: string): Photo {
  const photo = photos.find((candidate) => candidate.id === id);

  if (!photo) {
    throw new Error(`No photo with id "${id}" in photos.json. Did you run npm run photos?`);
  }

  return photo;
}
